USE fieldline;

CREATE TABLE IF NOT EXISTS toll_payment_events (
  id CHAR(36) PRIMARY KEY,
  payment_reference VARCHAR(120) NOT NULL,
  transaction_id CHAR(36) NOT NULL,
  related_notice_number VARCHAR(180) NOT NULL DEFAULT '',
  vehicle_id CHAR(36) NOT NULL,
  toll_account_id CHAR(36) NOT NULL,
  plate_number VARCHAR(40) NOT NULL DEFAULT '',
  passage_at DATETIME(3) NOT NULL,
  payment_at DATETIME(3) NOT NULL,
  payment_type VARCHAR(60) NOT NULL,
  payment_status VARCHAR(80) NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'USD',
  provider_payment_reference VARCHAR(180) NOT NULL DEFAULT '',
  ledger_entry_reference VARCHAR(180) NOT NULL DEFAULT '',
  payment_source VARCHAR(180) NOT NULL DEFAULT '',
  exception_code VARCHAR(80) NOT NULL DEFAULT '',
  investigation_notes TEXT NOT NULL,
  source_workbook VARCHAR(255) NOT NULL DEFAULT '',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY toll_payment_events_reference_unique (payment_reference),
  KEY toll_payment_events_account_date_idx (toll_account_id, payment_at),
  KEY toll_payment_events_vehicle_date_idx (vehicle_id, passage_at),
  CONSTRAINT toll_payment_events_transaction_fk FOREIGN KEY (transaction_id) REFERENCES toll_transactions(id),
  CONSTRAINT toll_payment_events_vehicle_fk FOREIGN KEY (vehicle_id) REFERENCES assets(id),
  CONSTRAINT toll_payment_events_account_fk FOREIGN KEY (toll_account_id) REFERENCES toll_accounts(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS toll_account_ledger (
  id CHAR(36) PRIMARY KEY,
  ledger_reference VARCHAR(120) NOT NULL,
  toll_account_id CHAR(36) NOT NULL,
  occurred_at DATETIME(3) NOT NULL,
  entry_type VARCHAR(40) NOT NULL,
  transaction_id CHAR(36) NULL,
  transaction_reference VARCHAR(180) NOT NULL DEFAULT '',
  payment_event_id CHAR(36) NULL,
  payment_reference VARCHAR(120) NOT NULL DEFAULT '',
  vehicle_id CHAR(36) NULL,
  external_reference VARCHAR(180) NOT NULL DEFAULT '',
  signed_amount DECIMAL(12,2) NOT NULL,
  running_balance DECIMAL(12,2) NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'USD',
  notes TEXT NOT NULL,
  source_workbook VARCHAR(255) NOT NULL DEFAULT '',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY toll_account_ledger_reference_unique (ledger_reference),
  KEY toll_account_ledger_account_date_idx (toll_account_id, occurred_at),
  CONSTRAINT toll_account_ledger_account_fk FOREIGN KEY (toll_account_id) REFERENCES toll_accounts(id),
  CONSTRAINT toll_account_ledger_transaction_fk FOREIGN KEY (transaction_id) REFERENCES toll_transactions(id) ON DELETE SET NULL,
  CONSTRAINT toll_account_ledger_payment_fk FOREIGN KEY (payment_event_id) REFERENCES toll_payment_events(id) ON DELETE SET NULL,
  CONSTRAINT toll_account_ledger_vehicle_fk FOREIGN KEY (vehicle_id) REFERENCES assets(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS toll_account_balance_snapshots (
  id CHAR(36) PRIMARY KEY,
  toll_account_id CHAR(36) NOT NULL,
  account_holder VARCHAR(180) NOT NULL DEFAULT '',
  account_status VARCHAR(30) NOT NULL,
  snapshot_at DATETIME(3) NOT NULL,
  opening_balance DECIMAL(12,2) NOT NULL,
  replenishment_credits DECIMAL(12,2) NOT NULL,
  settled_toll_debits DECIMAL(12,2) NOT NULL,
  calculated_ending_balance DECIMAL(12,2) NOT NULL,
  source_ending_balance DECIMAL(12,2) NOT NULL,
  balance_difference DECIMAL(12,2) NOT NULL,
  reconciliation_result VARCHAR(40) NOT NULL,
  successful_toll_charges INT UNSIGNED NOT NULL DEFAULT 0,
  failed_attempts INT UNSIGNED NOT NULL DEFAULT 0,
  currency CHAR(3) NOT NULL DEFAULT 'USD',
  source_workbook VARCHAR(255) NOT NULL DEFAULT '',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY toll_account_balance_snapshot_unique (toll_account_id, snapshot_at),
  CONSTRAINT toll_account_balance_snapshot_account_fk FOREIGN KEY (toll_account_id) REFERENCES toll_accounts(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
